// Package fide downloads FIDE's published rating-list files. It only ever fetches
// the download files, politely: conditional GETs, one request at a time, and a
// User-Agent that says who we are.
package fide

import (
	"crypto/sha256"
	"database/sql"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"net"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/msvens/mfide/internal/dao"
)

const userAgent = "mfide/0.1 (+https://github.com/msvens/mfide)"

// RatingTypes are the per-type archive lists, in FIDE's file-name spelling.
var RatingTypes = []string{"standard", "rapid", "blitz"}

// CurrentURL is the combined list (all three rating types), regenerated by FIDE
// regularly.
func CurrentURL(base string) string {
	return base + "/players_list_xml.zip"
}

// ArchiveURL is one rating type's list for one month, e.g. standard_sep26frl_xml.zip.
func ArchiveURL(base, ratingType string, period time.Time) string {
	return fmt.Sprintf("%s/%s_%s%02dfrl_xml.zip", base, ratingType,
		strings.ToLower(period.Format("Jan")), period.Year()%100)
}

// ErrNotFound is a 404: FIDE hasn't published the file (yet). This month's
// archive files appear in the first days of the month.
var ErrNotFound = errors.New("not found")

type Outcome int

const (
	New         Outcome = iota // new content, stored on disk
	Unchanged                  // 200, but the same bytes as last time
	NotModified                // 304 to our conditional GET
)

func (o Outcome) String() string {
	return [...]string{"new", "unchanged", "not modified"}[o]
}

type Fetcher struct {
	Client *http.Client
	Root   string // service.root; stored paths are relative to it
}

func NewFetcher(root string) *Fetcher {
	t := http.DefaultTransport.(*http.Transport).Clone()
	t.DialContext = (&net.Dialer{Timeout: 30 * time.Second}).DialContext
	t.TLSHandshakeTimeout = 30 * time.Second
	t.ResponseHeaderTimeout = time.Minute
	// No overall timeout: the combined list is ~50 MB and may arrive slowly.
	return &Fetcher{Client: &http.Client{Transport: t}, Root: root}
}

// Fetch does a conditional GET of url against prev (the latest file we have, or
// nil) and, if the content is new, stores it at destRel under Root. The returned
// file is not yet saved in the database. An existing file at destRel is never
// overwritten: the new one gets a .<sha8> suffix instead.
func (f *Fetcher) Fetch(url, destRel string, prev *dao.SourceFile) (Outcome, *dao.SourceFile, error) {
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return 0, nil, err
	}
	req.Header.Set("User-Agent", userAgent)
	if prev != nil {
		if prev.Etag != "" {
			req.Header.Set("If-None-Match", prev.Etag)
		}
		if prev.LastModified != nil {
			req.Header.Set("If-Modified-Since", prev.LastModified.UTC().Format(http.TimeFormat))
		}
	}
	resp, err := f.Client.Do(req)
	if err != nil {
		return 0, nil, err
	}
	defer func() { _ = resp.Body.Close() }()

	switch {
	case resp.StatusCode == http.StatusNotModified:
		return NotModified, nil, nil
	case resp.StatusCode == http.StatusNotFound:
		return 0, nil, fmt.Errorf("GET %s: %w", url, ErrNotFound)
	case resp.StatusCode != http.StatusOK:
		return 0, nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}

	dest := filepath.Join(f.Root, destRel)
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return 0, nil, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(dest), ".fetch-*")
	if err != nil {
		return 0, nil, err
	}
	// Removing after a successful rename is a no-op; otherwise it cleans up a
	// partial or unwanted download.
	defer func() { _ = os.Remove(tmp.Name()) }()

	h := sha256.New()
	size, err := io.Copy(io.MultiWriter(tmp, h), resp.Body)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return 0, nil, fmt.Errorf("download %s: %w", url, err)
	}
	sum := hex.EncodeToString(h.Sum(nil))
	if prev != nil && prev.Sha256 == sum {
		return Unchanged, prev, nil
	}

	if _, err := os.Stat(dest); err == nil {
		destRel += "." + sum[:8]
		dest = filepath.Join(f.Root, destRel)
	} else if !errors.Is(err, os.ErrNotExist) {
		return 0, nil, err
	}
	if err := os.Rename(tmp.Name(), dest); err != nil {
		return 0, nil, err
	}

	file := &dao.SourceFile{Url: url, Path: destRel, Size: size, Sha256: sum, Etag: resp.Header.Get("ETag")}
	if lm, err := http.ParseTime(resp.Header.Get("Last-Modified")); err == nil {
		file.LastModified = &lm
	}
	return New, file, nil
}

// sourceFiles is the part of dao.SourceFileDAO Download needs; tests fake it.
type sourceFiles interface {
	Latest(url string) (*dao.SourceFile, error)
	Insert(f *dao.SourceFile) error
	Touch(id int) error
}

// Target is one file to download: what it is and where it goes.
type Target struct {
	Kind       string
	RatingType *string
	Period     *time.Time
	Url        string
	DestRel    string
}

// Download fetches t against the latest file we have and records the result: a
// row for new content, a checked_at bump otherwise.
func Download(f *Fetcher, files sourceFiles, t Target) (Outcome, *dao.SourceFile, error) {
	prev, err := files.Latest(t.Url)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return 0, nil, err
	}
	outcome, file, err := f.Fetch(t.Url, t.DestRel, prev)
	if err != nil {
		return 0, nil, err
	}
	if outcome != New {
		if prev == nil {
			return 0, nil, fmt.Errorf("GET %s: %s without a previous file", t.Url, outcome)
		}
		return outcome, prev, files.Touch(prev.Id)
	}
	file.Kind, file.RatingType, file.Period = t.Kind, t.RatingType, t.Period
	return New, file, files.Insert(file)
}
